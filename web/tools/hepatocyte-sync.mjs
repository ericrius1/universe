// The well of liver cells (src/lab.ts) is drawn by the Hepatocyte project's own code on Universe's kit (its
// src/embed.ts: the plate on its bench, the wells, the field of cells on the chosen one's floor and what's inside them,
// and the Store that says what's in the well). A deploy builds this repo alone and Hepatocyte's has no remote, so a copy
// of what embed.ts reaches lives in src/well (its imports, types too, and its shaders' includes, followed from embed.ts:
// nothing of its own page), and this brings it up to date with Hepatocyte's checkout (commit it with the code that needs
// it). Never edit the copy: change it there, then run this. It loads no files of its own (the cells are made, not
// fetched), so nothing goes under public/.
//   npm run hepatocyte [path to Hepatocyte's src]     (default: the `embed` worktree beside this checkout's)
import { cpSync, rmSync, writeFileSync, existsSync, readFileSync, mkdirSync, statSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// (the `embed` worktree, hepatocyte-wt/embed, found in the nearest folder up from here that has it: the projects'
// folder, from this checkout or any worktree of it)
const embedSrc = () => { for (let d = here; d !== dirname(d); d = dirname(d)) { const c = join(d, 'hepatocyte-wt/embed/src'); if (existsSync(c)) return c; } return 'hepatocyte-wt/embed/src'; };
const src = resolve(process.argv[2] ?? embedSrc());
const dst = resolve(here, '../src/well');
const entry = resolve(src, 'embed.ts');
if (!existsSync(entry)) { console.error(`hepatocyte-sync: no embed.ts at ${src}`); process.exit(1); }

// the closure: ES imports and re-exports (types too: tsc reads them), workers, WGSL includes (written with or without
// their .wgsl) and their typings
const seen = new Set();
const queue = [entry];
const isFile = (p) => { try { return statSync(p).isFile(); } catch { return false; } };
const tsFile = (from, spec) => {
  const base = resolve(dirname(from), spec);
  for (const c of [base, `${base}.ts`, join(base, 'index.ts')]) if (isFile(c)) return c;
  return null;
};
while (queue.length) {
  const f = queue.pop();
  if (seen.has(f)) continue;
  seen.add(f);
  const text = readFileSync(f, 'utf8');
  if (f.endsWith('.wgsl')) {
    for (const m of text.matchAll(/^#include\s+"(\.{1,2}\/[^"]+)"/gm)) {
      const t = resolve(dirname(f), m[1]);
      queue.push(t.endsWith('.wgsl') ? t : `${t}.wgsl`);
    }
    const d = f.replace(/\.wgsl$/, '.d.wgsl.ts');
    if (existsSync(d)) seen.add(d);
    continue;
  }
  for (const m of text.matchAll(/(?:import|export)\s[^'"]*?from\s+'(\.{1,2}\/[^']+)'|import\s+'(\.{1,2}\/[^']+)'|new URL\('(\.{1,2}\/[^']+)',\s*import\.meta\.url\)|import\('(\.{1,2}\/[^']+)'\)/g)) {
    const spec = m[1] ?? m[2] ?? m[3] ?? m[4];
    const t = spec.endsWith('.wgsl') || spec.endsWith('.ts') ? resolve(dirname(f), spec) : tsFile(f, spec);
    if (t && existsSync(t)) queue.push(t); else console.warn(`hepatocyte-sync: ${relative(src, f)} → ${spec} not found`);
  }
}
rmSync(dst, { recursive: true, force: true });
for (const f of [...seen].sort()) {
  const to = resolve(dst, relative(src, f));
  mkdirSync(dirname(to), { recursive: true });
  // (a shader's typings say where they were made from: here, as this project's build writes them again)
  if (f.endsWith('.d.wgsl.ts')) writeFileSync(to, readFileSync(f, 'utf8').replace(/^\/\/ generated by weft from src\//, '// generated by weft from src/well/'));
  else cpSync(f, to);
}

let rev = 'unknown';
try { rev = execSync('git log -1 --format="%h %s"', { cwd: src }).toString().trim().slice(0, 140); } catch { /* not a checkout */ }
let dirty = '';
try { dirty = execSync('git status --porcelain -- .', { cwd: src }).toString().trim() ? ' (with uncommitted changes)' : ''; } catch { /* ignore */ }
writeFileSync(resolve(dst, 'VENDORED.md'), `Copied from the Hepatocyte project's src (embed.ts and what it reaches) by tools/hepatocyte-sync.mjs: edit it there, then \`npm run hepatocyte\`.\n\nHepatocyte ${rev}${dirty}\n`);
console.log(`hepatocyte-sync: ${seen.size} files → ${dst} ← Hepatocyte ${rev}${dirty}`);
