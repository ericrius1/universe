/** the map, w x h texels (rgba8, rows from the north pole down) */
export function rasterise(w: number, h: number): Uint8Array {
  const px = (lon: number) => ((lon + 180) / 360) * w, py = (lat: number) => ((90 - lat) / 180) * h;
  // (one canvas per channel: each a grey picture, drawn with its rings at three longitudes so they wrap)
  const layer = (paint: (fill: (r: Ring, v: number, mode?: GlobalCompositeOperation) => void, ctx: CanvasRenderingContext2D) => void) => {
    const cv = typeof document === 'undefined' ? new OffscreenCanvas(w, h) : document.createElement('canvas');
    cv.width = w; cv.height = h;
    const ctx = cv.getContext('2d', { willReadFrequently: true }) as CanvasRenderingContext2D;
    ctx.fillStyle = '#000';
    ctx.fillRect(0, 0, w, h);
    const fill = (r: Ring, v: number, mode: GlobalCompositeOperation = 'source-over') => {
      ctx.globalCompositeOperation = mode;
      const g = Math.round(Math.max(0, Math.min(1, v)) * 255);
      ctx.fillStyle = `rgb(${g},${g},${g})`;
      for (const k of [-360, 0, 360]) {
        ctx.beginPath();
        for (let i = 0; i < r.length; i += 2) ctx.lineTo(px(r[i] + k), py(r[i + 1]));
        ctx.closePath();
        ctx.fill();
      }
    };
    paint(fill, ctx);
    const d = ctx.getImageData(0, 0, w, h).data, out = new Float32Array(w * h);
    for (let i = 0; i < out.length; i++) out[i] = d[i * 4] / 255;
    return out;
  };
  const land = layer((fill) => {
    for (const r of LAND) fill(r, 1);
    for (const r of WATER) fill(r, 0);
    for (const r of SEA_ISLANDS) fill(r, 1);
  });
  const dry = layer((fill) => { for (const [r, v] of DRY) fill(r, v, 'lighten'); });
  const ice = layer((fill) => { for (const [r, v] of [...MOUNTAINS, ...ICE]) fill(r, v, 'lighten'); });
  const lights = layer((fill, ctx) => {
    for (const [r, v] of COUNTRYSIDE) fill(r, v * 0.25, 'lighten');
    ctx.globalCompositeOperation = 'lighter';
    // (a dot ~20-50 km across, brightest at its heart; its longitude stretched as the parallels shrink)
    for (let i = 0; i < CITIES.length; i += 3) {
      const x = px(CITIES[i]), y = py(CITIES[i + 1]), s = CITIES[i + 2];
      const rad = (0.35 + 0.75 * s) * (w / 2048);
      const g = ctx.createRadialGradient(x, y, 0, x, y, rad * 2);
      g.addColorStop(0, `rgba(255,255,255,${0.35 + 0.65 * s})`);
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g;
      ctx.save();
      ctx.translate(x, y);
      ctx.scale(1 / Math.max(Math.cos((CITIES[i + 1] * Math.PI) / 180), 0.2), 1);
      ctx.translate(-x, -y);
      ctx.fillRect(x - rad * 2, y - rad * 2, rad * 4, rad * 4);
      ctx.restore();
    }
  });
  // soft coasts and borders: box blurs, a few texels for the land and the ice, wider for the deserts' edges
  blur(land, w, h, 1, 2);
  blur(ice, w, h, 1, 2);
  blur(dry, w, h, 5, 3);
  blur(lights, w, h, 2, 2);
  const out = new Uint8Array(w * h * 4);
  const b = (v: number) => Math.round(Math.max(0, Math.min(1, v)) * 255);
  for (let i = 0; i < w * h; i++) {
    out[i * 4] = b(land[i]); out[i * 4 + 1] = b(dry[i]); out[i * 4 + 2] = b(lights[i]); out[i * 4 + 3] = b(ice[i]);
  }
  return out;
}

/** an RGBA map's mip chain (the map first, down to a texel), each a box filter of the one before: columns wrap round the
 *  globe, rows clamp at the poles */
export function mips(px: Uint8Array, w: number, h: number): Uint8Array[] {
  const out = [px];
  let src = px, sw = w, sh = h;
  while (sw > 1 || sh > 1) {
    const dw = Math.max(1, sw >> 1), dh = Math.max(1, sh >> 1), dst = new Uint8Array(dw * dh * 4);
    for (let y = 0; y < dh; y++) {
      const r0 = Math.min(2 * y, sh - 1) * sw * 4, r1 = Math.min(2 * y + 1, sh - 1) * sw * 4;
      for (let x = 0; x < dw; x++) {
        const c0 = ((2 * x) % sw) * 4, c1 = ((2 * x + 1) % sw) * 4, o = (y * dw + x) * 4;
        for (let c = 0; c < 4; c++) dst[o + c] = (src[r0 + c0 + c] + src[r0 + c1 + c] + src[r1 + c0 + c] + src[r1 + c1 + c] + 2) >> 2;
      }
    }
    out.push(dst);
    src = dst; sw = dw; sh = dh;
  }
  return out;
}

/** a box blur of radius r texels, `passes` times over (rows wrap round the globe, columns clamp at the poles) */
function blur(a: Float32Array, w: number, h: number, r: number, passes: number) {
  const tmp = new Float32Array(Math.max(w, h));
  const n = 2 * r + 1;
  for (let p = 0; p < passes; p++) {
    for (let y = 0; y < h; y++) {
      const o = y * w;
      let s = 0;
      for (let k = -r; k <= r; k++) s += a[o + ((k + w) % w)];
      for (let x = 0; x < w; x++) {
        tmp[x] = s / n;
        s += a[o + ((x + r + 1) % w)] - a[o + ((x - r + w) % w)];
      }
      a.set(tmp.subarray(0, w), o);
    }
    for (let x = 0; x < w; x++) {
      let s = 0;
      for (let k = -r; k <= r; k++) s += a[Math.min(h - 1, Math.max(0, k)) * w + x];
      for (let y = 0; y < h; y++) {
        tmp[y] = s / n;
        s += a[Math.min(h - 1, y + r + 1) * w + x] - a[Math.max(0, y - r) * w + x];
      }
      for (let y = 0; y < h; y++) a[y * w + x] = tmp[y];
    }
  }
}
